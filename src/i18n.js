function fill(text, params = {}) {
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    name in params ? String(params[name]) : match,
  );
}

/** The theme's own string in `language`, falling back to English. */
export function themeText(language, key, params) {
  return fill(strings[language]?.[key] ?? strings.en[key] ?? key, params);
}

/** A host string. The host returns the key itself for keys it does not know;
    then the English fallback from hostKeys is shown instead. Action labels
    from sdk.host.listActions() (labelKey) work the same way. */
export function hostText(sdk, key, params) {
  const text = sdk.i18n.t(key, params);
  return text && text !== key ? text : fill(hostKeys[key] ?? key, params);
}

